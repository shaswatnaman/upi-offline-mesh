package com.shaswatnaman.upimesh.model;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.Instant;

/**
 * ============================================================
 * CONCEPT: OOP — Class as a Blueprint for a Database Row
 * ============================================================
 * This class demonstrates multiple OOP concepts:
 *
 * 1. CLASS: Transaction is a blueprint. Each row in the 'transactions'
 *    table becomes one Transaction OBJECT (instance) in memory.
 *
 * 2. ENCAPSULATION: All fields are private. Outside code accesses them
 *    only via getters/setters (generated by @Getter/@Setter from Lombok).
 *    The DB enforces constraints (@Column nullable=false) — data integrity
 *    is baked into the class definition, not scattered across the code.
 *
 * 3. ABSTRACTION: Callers just call repo.save(transaction). They don't
 *    know about SQL INSERT statements — that's hidden by JPA/Hibernate.
 *
 * 4. ENUM (inner class): Status is a nested enum (a type-safe set of
 *    constants). Instead of storing "SETTLED"/"REJECTED" as raw strings
 *    (error-prone), we use Status.SETTLED — the compiler checks it.
 *
 * SQL CONCEPT:
 *   @Table(name="transactions") → maps this class to the SQL table.
 *   @Column(unique=true) on packetHash → SQL UNIQUE constraint, prevents
 *   duplicate payments at the DB level even if code logic fails.
 *   @Index → creates a DB index on packetHash for fast lookup.
 * ============================================================
 */
@Entity
@Table(name = "transactions",
        indexes = { @Index(name = "idx_packet_hash", columnList = "packetHash", unique = true) })
@Getter
@Setter
@NoArgsConstructor
public class Transaction {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, unique = true, length = 64)
    private String packetHash; // SHA-256 hex of the encrypted packet

    @Column(nullable = false)
    private String senderVpa;

    @Column(nullable = false)
    private String receiverVpa;

    @Column(nullable = false, precision = 19, scale = 2)
    private BigDecimal amount;

    @Column(nullable = false)
    private Instant signedAt; // When the sender originally signed it (offline)

    @Column(nullable = false)
    private Instant settledAt; // When the backend actually processed it

    @Column(nullable = false)
    private String bridgeNodeId; // Which mesh node finally delivered it

    @Column(nullable = false)
    private int hopCount; // How many devices it passed through

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private Status status;

    public enum Status { SETTLED, REJECTED }
}
